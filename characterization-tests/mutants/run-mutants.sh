#!/usr/bin/env bash
# Mutation check: proves the characterisation tests can fail. Each mutant is ONE deliberate defect applied to a throwaway
# copy of legacy-app, built into its own image and run beside the real stack. The suite must go red for every mutant.
# Usage: characterization-tests/mutants/run-mutants.sh   (needs docker compose postgres running)
# Output: characterization-tests/mutants/RESULTS.md (generated, never edited by hand)
set -uo pipefail
cd "$(dirname "$0")/../.."
ROOT="$PWD"
NET="$(docker compose ps -q postgres | head -1 | xargs docker inspect -f '{{range $k,$v := .NetworkSettings.Networks}}{{$k}}{{end}}')"
PORT=18081
OUT="$ROOT/characterization-tests/mutants/RESULTS.md"
WORK="$(mktemp -d)"
trap 'docker rm -f harbor-mutant >/dev/null 2>&1; rm -rf "$WORK"' EXIT

# name | file (under legacy-app) | exact text to find | replacement
MUTANTS=(
 "page-size-11|src/main/java/com/harborclaims/portal/common/Paging.java|PAGE_SIZE = 10|PAGE_SIZE = 11"
 "customer-order-ignores-first-name|src/main/java/com/harborclaims/portal/customers/CustomerDao.java|ORDER BY last_name, first_name, id|ORDER BY last_name, id"
 "claims-sorted-newest-first|src/main/java/com/harborclaims/portal/claims/ClaimDao.java|ORDER BY cl.id LIMIT|ORDER BY cl.id DESC LIMIT"
 "status-filter-case-folded|src/main/java/com/harborclaims/portal/common/SearchForm.java|return status == null ? \"\" : status.trim();|return status == null ? \"\" : status.trim().toUpperCase();"
 "search-term-not-trimmed|src/main/java/com/harborclaims/portal/common/SearchForm.java|return q == null ? \"\" : q.trim();|return q == null ? \"\" : q;"
 "claim-number-match-case-sensitive|src/main/java/com/harborclaims/portal/claims/ClaimDao.java|lower(cl.claim_number) LIKE lower('%|cl.claim_number LIKE ('%"
 "delete-open-to-every-role|src/main/webapp/WEB-INF/struts-config.xml|type=\"com.harborclaims.portal.customers.CustomerDeleteAction\"
            roles=\"ADMIN\">|type=\"com.harborclaims.portal.customers.CustomerDeleteAction\">"
 "duplicate-email-not-checked|src/main/java/com/harborclaims/portal/customers/CustomerManager.java|if (dao.emailInUse(c.getEmail(), c.getId())) {|if (false) {"
 "not-found-becomes-bad-request|src/main/java/com/harborclaims/portal/common/BaseAction.java|HttpServletResponse.SC_NOT_FOUND|HttpServletResponse.SC_BAD_REQUEST"
 "login-redirect-carries-a-return-url|src/main/java/com/harborclaims/portal/auth/LoginFilter.java|request.getContextPath() + \"/login.do\"|request.getContextPath() + \"/login.do?from=\" + path"
 "state-not-upper-cased|src/main/java/com/harborclaims/portal/customers/CustomerForm.java|state.trim().toUpperCase()|state.trim()"
)

{
  echo "# Mutation check results"
  echo
  echo "Generated by \`characterization-tests/mutants/run-mutants.sh\`. Each mutant is one deliberate defect in a throwaway copy of the legacy app."
  echo "A mutant is KILLED when the characterisation suite goes red, SURVIVED when it stays green (a gap in the tests)."
  echo
  echo "| Mutant | Result | Failing tests (first few) |"
  echo "|---|---|---|"
} > "$OUT"

survived=0
for spec in "${MUTANTS[@]}"; do
  IFS='|' read -r name file find replace <<<"$spec"
  echo "=== mutant: $name"
  rm -rf "$WORK/app"; mkdir -p "$WORK/app"
  (cd legacy-app && tar --exclude=./target -cf - .) | (cd "$WORK/app" && tar xf -)
  if ! python3 - "$WORK/app/$file" "$find" "$replace" <<'PY'
import sys
path, find, repl = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(path).read()
if find not in s:
    sys.exit("mutation text not found in " + path)
open(path, "w").write(s.replace(find, repl, 1))
PY
  then echo "| $name | NOT APPLIED | mutation text not found |" >> "$OUT"; survived=$((survived+1)); continue; fi
  sed -i.bak 's/mvn -B -q package/mvn -B -q -Dmaven.test.skip=true package/' "$WORK/app/Dockerfile"
  if ! docker build -q -t harbor-mutant "$WORK/app" >/dev/null 2>"$WORK/build.err"; then
    echo "| $name | BUILD FAILED | $(grep -v '^$' "$WORK/build.err" | head -3 | tr '|\n' '  ') |" >> "$OUT"; survived=$((survived+1)); continue
  fi
  docker rm -f harbor-mutant >/dev/null 2>&1
  docker run -d --name harbor-mutant --network "$NET" -p "$PORT:8080" \
    -e JAVA_OPTS="-Duser.timezone=UTC -Dharbor.jobs.enabled=false -Dharbor.db.url=jdbc:postgresql://postgres:5432/${POSTGRES_DB:-harbor} -Dharbor.db.user=harbor_app -Dharbor.db.password=${APP_DB_PASSWORD:-change-me-app-local}" \
    harbor-mutant >/dev/null
  if ! scripts/wait-ready.sh "http://localhost:$PORT" 120 >/dev/null; then
    echo "| $name | DID NOT START | the mutated app never became ready |" >> "$OUT"; survived=$((survived+1)); continue
  fi
  rm -rf characterization-tests/target/surefire-reports
  mvn -B -q -f characterization-tests/pom.xml test -Dbase.url="http://localhost:$PORT" -Dtarget=legacy -Dorder.seed=1 >/dev/null 2>&1
  status=$?
  failing="$(python3 characterization-tests/mutants/failing_tests.py characterization-tests/target/surefire-reports)"
  if [ "$status" -ne 0 ]; then
    echo "| $name | KILLED | ${failing:-suite failed} |" >> "$OUT"
  else
    echo "| $name | **SURVIVED** | - |" >> "$OUT"; survived=$((survived+1))
  fi
  docker rm -f harbor-mutant >/dev/null 2>&1
done

echo >> "$OUT"
echo "Survivors, build failures and mutants that did not apply: $survived" >> "$OUT"
cat "$OUT"
[ "$survived" -eq 0 ]
